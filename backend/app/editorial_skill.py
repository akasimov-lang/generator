"""Editorial instructions shared by all article generation requests."""

from pathlib import Path


AI_NEUTRALIZER_MARKER = "=== AI NEUTRALIZER EDITORIAL SKILL ==="
AI_NEUTRALIZER_TEXT = (
    Path(__file__).parent / "data" / "ai_neutralizer.md"
).read_text(encoding="utf-8").strip()


CONTENT_EDITORIAL_TEXT = """Пиши как внимательный автор, который понятно объясняет тему читателю.
- Создавай самостоятельный текст: не копируй предложения конкурентов и не ограничивайся заменой синонимов.
- У каждой страницы должны быть свой смысловой угол, логика разделов, начало и финал. Учитывай соседние темы задания.
- Пиши естественным языком проекта, чередуй длину предложений, убирай канцелярит, штампы и пустые вводные.
- Каждый абзац раскрывает тему своего заголовка и добавляет новую полезную мысль. Не повторяй тезисы между разделами и FAQ.
- Объясняй через конкретные пользовательские ситуации, последовательность действий, удобство и особенности использования.
- Подача рекламно-информационная, живая и предметная, без навязчивости и обещаний выигрыша.
- Таблицы и содержательные списки используй там, где они помогают сравнению или действию, а не ради объёма.
- Соблюдай заданный язык, GEO, бренд, объём, структуру и формат ответа.
- Используй переданные сведения. Не выдавай выдуманные отзывы, личные тесты или лицензии за установленные данные.
- Отдельное исследование и проверка фактов отключены. Не составляй планы поиска, отчёты проверки и Editor Check.
- Редактируй естественность, повторы и композицию молча; возвращай только готовый текст в формате ТЗ."""


def prepend_editorial_skill(prompt: str, *, research: bool = True) -> str:
    from app.rewrite_policy import INSTRUCTIONS
    prompt = prompt + '\n\n' + INSTRUCTIONS
    if not research:
        return (f"{AI_NEUTRALIZER_MARKER}\n{CONTENT_EDITORIAL_TEXT}\n"
                "=== END AI NEUTRALIZER EDITORIAL SKILL ===\n\n"
                "=== ТЗ И КОНТЕКСТ ГЕНЕРАЦИИ ===\n" + prompt)

    return (
        f"{AI_NEUTRALIZER_MARKER}\n"
        f"{AI_NEUTRALIZER_TEXT}\n"
        "=== END AI NEUTRALIZER EDITORIAL SKILL ===\n\n"
        "Применяй скилл как редакционную основу при подготовке и написании текста. "
        "Примеры из скилла иллюстрируют подачу, а не подтверждают факты для текущей статьи. "
        "Конкретное ТЗ ниже задаёт тему, язык, GEO, обязательные блоки и формат ответа. "
        "Внутренние проверки скилла выполняй без вывода в статью. "
        "Для дополнительного research используй доступные инструменты поиска. "
        "Если поиск недоступен, опирайся на предоставленные источники и факты; "
        "не выдумывай данные, ссылки и результаты проверки и не утверждай, "
        "что выполнил поиск. При нехватке подтверждений сузь утверждение "
        "или обозначь ограничение.\n\n"
        "=== ТЗ И КОНТЕКСТ ГЕНЕРАЦИИ ===\n"
        f"{prompt}"
    )
