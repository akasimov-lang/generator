export default function UserGuide() {
  const slug = window.location.pathname.replace(/\/+$/, "").split("/")[2] || "";
  const article = guides.find(item => item.slug === slug);
  function navigate(event: React.MouseEvent<HTMLAnchorElement>) {
    if (event.button || event.metaKey || event.ctrlKey || event.shiftKey || event.altKey) return;
    event.preventDefault();
    window.history.pushState(null, "", event.currentTarget.getAttribute("href")!);
    window.dispatchEvent(new PopStateEvent("popstate"));
    window.scrollTo(0, 0);
  }
  const link = (item: Guide) => <li key={item.slug}><a href={`/guide/${item.slug}`} onClick={navigate}>
    <span><strong>{item.title}</strong><small>{item.summary}</small></span><ArrowRight size={18} aria-hidden="true" />
  </a></li>;

  return <div className="userGuidePage guideHub">
    <header className="guideSection">
      <span className="guideKicker"><BookOpen size={18} /> PagePilot · Инструкции</span>
      <h2>{article?.title || (slug ? "Инструкция не найдена" : "Как работать с PagePilot")}</h2>
      <p>{article?.summary || (slug ? "Выберите нужную тему в общем списке." : "Начните с базового руководства или выберите инструкцию для своей задачи. У каждой темы отдельная ссылка.")}</p>
      {slug ? <a className="button secondary" href="/guide" onClick={navigate}><ArrowLeft size={16} /> Все инструкции</a>
        : <a className="button primary" href="/guide/start" onClick={navigate}>Открыть базовую инструкцию <ArrowRight size={16} /></a>}
    </header>
    {article ? <article className="guideSection guideArticle">
      <nav className="guideContents" aria-label="В этой инструкции">{article.sections.map((section, index) =>
        <a key={index} href={`#section-${index}`}>{section.title}</a>)}</nav>
      {article.sections.map((section, index) => <section key={index} id={`section-${index}`}>
        <h3>{section.title}</h3>{section.text ? <p>{section.text}</p> : null}
        {section.steps ? <ol>{section.steps.map(step => <li key={step}>{step}</li>)}</ol> : null}
      </section>)}
      <a href="/auto-reglue/guide" onClick={navigate}>Подробная инструкция по автопереклеям →</a>
    </article> : !slug ? <nav aria-label="Инструкции по темам">
      {["Начало работы", "Контент и меню", "Домены и переклеи", "Помощь"].map(group =>
        <section className="guideSection guideTopicGroup" key={group}>
          <h2>{group}</h2><ul className="guideTopicList">
            {guides.filter(item => item.group === group).map(link)}
            {group === "Домены и переклеи" ? <li><a href="/auto-reglue/guide" onClick={navigate}><span>
              <strong>Автопереклеи: настройки, схемы и расписание</strong>
              <small>Однократный и периодический запуск, персональные правила, имена поддоменов, фейковые страницы и индексация.</small>
            </span><ArrowRight size={18} aria-hidden="true" /></a></li> : null}
          </ul>
        </section>)}
    </nav> : null}
  </div>;
}
